"""Derive per-unit world-map icons from the confirmed row-4 combat sprite by
rotating it (vertical and diagonal) so they always match the unit."""
import os, json
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
b = open(os.path.join(ROOT, 'dump', 'spritebank.bin'), 'rb').read()
pal = json.load(open(os.path.join(ROOT, 'assets', 'art', 'palette.json')))
PAL = [(p['r'], p['g'], p['b']) for p in pal]
OUT = os.path.join(ROOT, 'assets', 'units')

def tile(idx, bank=9):
    im = Image.new('RGBA', (32, 32), (0, 0, 0, 0)); px = im.load(); off = idx * 1024
    for y in range(32):
        for x in range(32):
            v = b[off + y * 32 + x]
            if v:
                px[x, 31 - y] = PAL[((bank << 4) | (v & 0xF)) & 0xFF] + (255,)
    return im

def centered_rot(im, angle):
    r = im.rotate(angle, resample=Image.NEAREST, expand=True)
    out = Image.new('RGBA', (32, 32), (0, 0, 0, 0))
    out.paste(r, ((32 - r.width) // 2, (32 - r.height) // 2), r)
    return out

for t in range(24):
    src = tile(160 + (t if t < 23 else 0))
    vert = centered_rot(src, 90)
    diag = centered_rot(src, 45)
    strip = Image.new('RGBA', (64, 32), (0, 0, 0, 0))
    strip.paste(vert, (0, 0), vert)
    strip.paste(diag, (32, 0), diag)
    folder = os.path.join(OUT, 'unit_%02d' % t)
    strip.save(os.path.join(folder, 'world_map.png'))
    meta_path = os.path.join(folder, 'unit.json')
    meta = json.load(open(meta_path, encoding='utf-8'))
    meta['world_map'] = 'rotated from combat sprite'
    meta.pop('world_map_tiles', None)
    meta.pop('world_map_sprites', None)
    json.dump(meta, open(meta_path, 'w', encoding='utf-8'), indent=2, ensure_ascii=False)
print('world_map strips regenerated by rotating row-4 sprites')
